// Measures every persona's situation frequencies and writes lib/agent/read/population.ts.
//   node --disable-warning=MODULE_TYPELESS_PACKAGE_JSON --import ./lib/poker/scripts/register-ts.mjs lib/agent/read/scripts/measure.ts
// 200,000 heads-up hands per persona (vs TAG) and 200,000 6-max hands, one worker per job (~1 min).

import { writeFileSync } from "node:fs";
import { PERSONA_IDS, type PersonaId } from "../../../bots/personas";
import { measureHeadsUp, measureSixMax, type SituationCounts } from "../truth";
import { isMainThread, runJobs, serveJobs } from "./parallel";

const HU_HANDS = 200_000;
const SIX_MAX_HANDS = 200_000;
const HU_SEED = 1_000; // + persona index
const SIX_MAX_SEED = 6_000;

type Job = { kind: "hu"; persona: PersonaId; seed: number } | { kind: "6max" };

function run(job: Job): SituationCounts | Record<PersonaId, SituationCounts> {
  return job.kind === "hu" ? measureHeadsUp(job.persona, HU_HANDS, job.seed) : measureSixMax(SIX_MAX_HANDS, SIX_MAX_SEED);
}

const table = (name: string, counts: Record<PersonaId, SituationCounts>) =>
  `export const ${name}: Readonly<Record<PersonaId, SituationCounts>> = {\n${PERSONA_IDS.map((id) => `  ${id}: ${JSON.stringify(counts[id])},`).join("\n")}\n};\n`;

async function main() {
  const jobs: Job[] = [{ kind: "6max" }, ...PERSONA_IDS.map((persona, i): Job => ({ kind: "hu", persona, seed: HU_SEED + i }))];
  const results = await runJobs<Job, SituationCounts | Record<PersonaId, SituationCounts>>(import.meta.url, jobs);
  const sixMax = results[0] as Record<PersonaId, SituationCounts>;
  const hu = Object.fromEntries(PERSONA_IDS.map((id, i) => [id, results[i + 1]])) as Record<PersonaId, SituationCounts>;
  const source = `// Generated by lib/agent/read/scripts/measure.ts; do not edit by hand. See truth.ts for the setups.
// counts[situation][outcome], situations and outcomes in the order of SITUATIONS (situations.ts).

import type { PersonaId } from "../../bots/personas";
import type { SituationCounts } from "./truth";

export const POPULATION_SAMPLE = { huHands: ${HU_HANDS}, huSeed: ${HU_SEED}, sixMaxHands: ${SIX_MAX_HANDS}, sixMaxSeed: ${SIX_MAX_SEED} } as const;

/** Heads-up vs TAG, the persona in seat 0 (seed huSeed + persona index in PERSONA_IDS). */
${table("HU_COUNTS", hu)}
/** 6-max, one of each persona, reseated every hand. */
${table("SIX_MAX_COUNTS", sixMax)}`;
  writeFileSync(new URL("../population.ts", import.meta.url), source);
  console.log("wrote lib/agent/read/population.ts");
}

if (isMainThread) await main();
else serveJobs(run);
